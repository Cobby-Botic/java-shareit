CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(512) NOT NULL,
  CONSTRAINT pk_user PRIMARY KEY (id),
  CONSTRAINT UQ_USER_EMAIL UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(512) NOT NULL,
  owner BIGINT NOT NULL,
  available BOOLEAN,
  CONSTRAINT fk_users FOREIGN KEY (owner) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS booking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  itemID BIGINT NOT NULL,
  booker_id BIGINT NOT NULL,
  date_from TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  date_to TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  status VARCHAR(64),
  CONSTRAINT fk_items FOREIGN KEY (itemID) REFERENCES items(id),
  CONSTRAINT fk_users FOREIGN KEY (booker_id) REFERENCES users(id)
);